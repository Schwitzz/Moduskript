def default_icon_color(accent=False):
    """Return hex colour string for icons based on the active colour scheme."""
    try:
        s, d = Appearance.colours()
        if s is not None:
            return d.get("accent", s.accent) if accent else s.text
    except Exception:
        pass
    return "#6ea8fe" if accent else "#e4e6eb"


def pixmap(name, size=20, color=None, accent=False):
    """Render a named Lucide icon to a `QPixmap` of `size x size`."""
    body = LUCIDE_PATHS.get(name, LUCIDE_PATHS["sparkles"])
    stroke = color or default_icon_color(accent=accent)
    svg = (
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{size}" height="{size}" '
        f'viewBox="0 0 24 24" fill="none" stroke="{stroke}" stroke-width="2" '
        f'stroke-linecap="round" stroke-linejoin="round">{body}</svg>'
    )
    pm = QPixmap(QSize(size, size))
    pm.fill(Qt.transparent)
    renderer = QSvgRenderer(QByteArray(svg.encode("utf-8")))
    painter = QPainter(pm)
    painter.setRenderHint(QPainter.Antialiasing)
    renderer.render(painter, QRectF(0, 0, size, size))
    painter.end()
    return pm


def icon(name, size=20, color=None, accent=False):
    """Return a `QIcon` rendered from the modern Lucide vector path."""
    return QIcon(pixmap(name, size=size, color=color, accent=accent))
